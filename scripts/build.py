def session_page(event, day, solves, notes, avg, trimmed, st, prev):
    counted_std = np.std([s["time"] for i, s in enumerate(solves) if i not in trimmed], ddof=1)
    L = [f"# {event} PB — {fmt(avg)}", "", f"**Date:** {day}  "]
    if prev:
        L.append(f"**Previous PB:** {fmt(prev['average'])} ({prev['date']}) · "
                 f"improved by **{prev['average'] - avg:.2f}s**  ")
    L += [f"[← all records](../../../README.md)", ""]
    for note in notes:
        L.append(f"> {note}")
    if notes:
        L.append("")
    L += ["## Stats", "",
          "| | |", "|---|---|",
          f"| **{event} (official, trimmed)** | **{fmt(avg)}** |",
          f"| Solves | {st['n']} (trimmed {trim_count(st['n'])} from each end) |",
          f"| Mean (all solves) | {st['mean']:.2f} |",
          f"| Median | {st['median']:.2f} |",
          f"| Std dev (σ, all solves) | {st['std']:.2f} |",
          f"| Std dev (σ, counted solves only) | {counted_std:.2f} |",
          f"| **Consistency: σ / mean** | **{100 * st['cv']:.1f}%** |",
          f"| Consistency, outlier-proof: IQR / median | {100 * st['robust_cv']:.1f}% |",
          f"| Min / Best | {fmt(st['min'])} |",
          f"| Q1 (25th pct) | {st['q1']:.2f} |",
          f"| Q3 (75th pct) | {st['q3']:.2f} |",
          f"| Max / Worst | {fmt(st['max'])} |",
          f"| IQR (Q3 − Q1) | {st['iqr']:.2f} |",
          f"| Range | {st['range']:.2f} |"]
    if st["dnf"]:
        L.append(f"| DNFs | {st['dnf']} |")
    if st["n"] >= 8:
        L.append(f"| Skewness | {st['skew']:+.2f} |")
        L.append(f"| Shapiro–Wilk p (normality) | {st['shapiro_p']:.3f} |")
    finite = [s["time"] for s in solves if math.isfinite(s["time"])]
    thresholds = [t for t in range(int(min(finite)) + 1, int(max(finite)) + 2)][:6]
    subs = " · ".join(f"sub-{t}: {sum(x < t for x in finite)}" for t in thresholds)
    L += ["", f"**Sub-X counts:** {subs}", ""]
    if st["n"] >= 8:
        L += ["<sub>Skewness > 0 means a longer tail of slow solves (typical for cubing). "
              "Shapiro–Wilk p < 0.05 means the times are unlikely to be normally distributed.</sub>",
              ""]
    L += ["## Distribution", "", "![distribution](distribution.png)", "",
          "## Solves in order", "", "![sequence](sequence.png)", "",
          *recon_section(solves, trimmed),
          "## Solves", "", "| # | Time | Scramble |" if any(s["scramble"] for s in solves)
          else "| # | Time |",
          "|---|---|---|" if any(s["scramble"] for s in solves) else "|---|---|"]
    for i, s in enumerate(solves):
        t = fmt(s["time"]) + ("+" if s["penalty"] == "+2" else "")
        t = f"({t})" if i in trimmed else f"**{t}**"
        row = f"| {i + 1} | {t} |"
        if s["scramble"]:
            row += f" `{s['scramble']}` |"
        L.append(row)
    L += ["", "<sub>Bold = counted, (parentheses) = trimmed. `+` = includes a +2 penalty.</sub>", ""]
    return "\n".join(L)


def single_page(day, solve, notes, prev):
    L = [f"# Single PB — {fmt(solve['time'])}", "", f"**Date:** {day}  "]
    if prev:
        L.append(f"**Previous PB:** {fmt(prev['average'])} ({prev['date']}) · "
                 f"improved by **{prev['average'] - solve['time']:.2f}s**  ")
    L += ["[← all records](../../../README.md)", ""]
    L += [f"> {n}" for n in notes] + ([""] if notes else [])
    L += [f"**Scramble:** `{solve['scramble']}`", ""]
    L += recon_section([solve]) or [
        "_No reconstruction yet. Add `>` lines under the solve in the record file to include one._", ""]
    return "\n".join(L)


def fast_solves_page():
    files = sorted((ROOT / "fast-solves").glob("*.txt"), key=file_key, reverse=True)
    L = ["# Fast solve bank", "",
         "Hand-picked good solves (not PBs, not averages), newest first. "
         "Generated by `scripts/build.py`.", "",
         "[← all records](../README.md)", ""]
    entries = []
    for f in files:
        solves, notes, _ = parse_file(f)
        if len(solves) != 1:
            raise SystemExit(f"{f}: a fast-solve file holds exactly one solve")
        entries.append((f, solves[0], notes))
    recon = [(f, s, analyze_recon(s["recon"])) for f, s, _ in entries if s["recon"]]
    if recon:
        stm = [a["stm"] for _, _, a in recon]
        tps = [a["stm"] / s["time"] for _, s, a in recon]
        L += ["## Across the bank", "",
              "| Solves | Reconstructed | Mean time | Mean moves (STM) | Fewest moves | "
              "Mean TPS | Highest TPS | Mean rotations |", "|---|---|---|---|---|---|---|---|",
              f"| {len(entries)} | {len(recon)} | "
              f"{np.mean([s['time'] for _, s, _ in entries]):.2f} | {np.mean(stm):.1f} | "
              f"{min(stm)} | {np.mean(tps):.2f} | {max(tps):.2f} | "
              f"{np.mean([a['rotations'] for _, _, a in recon]):.1f} |", ""]
        crosses = [a["cross"] for _, _, a in recon if a["labelled"] and a["cross"]]
        pp = [a["per_pair"] for _, _, a in recon if a["per_pair"]]
        lls = [a["ll"] for _, _, a in recon if a["labelled"] and a["ll"]]
        if crosses or pp or lls:
            L += ["| Mean cross | Mean moves per F2L pair | Mean last layer |", "|---|---|---|",
                  f"| {np.mean(crosses):.1f} | {np.mean(pp):.1f} | {np.mean(lls):.1f} |"
                  .replace("nan", "—"), ""]
    if entries:
        L += ["## All fast solves", "",
              "| Date | Time | Moves (STM) | TPS | Rotations | Cross | Moves/pair | LL | Notes |",
              "|---|---|---|---|---|---|---|---|---|"]
        for f, s, notes in entries:
            a = analyze_recon(s["recon"]) if s["recon"] else None
            anchor = "#" + re.sub(r"[^a-z0-9 -]", "", f"{file_label(f)} {fmt(s['time'])}"
                                  .lower()).replace(" ", "-")
            cells = ([str(a["stm"]), f"{a['stm'] / s['time']:.2f}", str(a["rotations"]),
                      str(a["cross"]) if a["labelled"] else "—",
                      f"{a['per_pair']:.1f}" if a["per_pair"] else "—",
                      str(a["ll"]) if a["labelled"] else "—"] if a else ["—"] * 6)
            L.append(f"| [{file_label(f)}]({anchor}) | **{fmt(s['time'])}** | "
                     + " | ".join(cells) + f" | {'; '.join(notes)} |")
        L.append("")
        for f, s, notes in entries:
            heading = f"### {file_label(f)} — {fmt(s['time'])}"
            if s["recon"]:
                L += recon_block(s, heading)
            else:
                L += [heading, "", f"**Scramble:** `{s['scramble']}`", "",
                      "_No reconstruction._", ""]
            L += [f"> {n}" for n in notes] + ([""] if notes else [])
    else:
        L += ["_No fast solves yet._", ""]
    return "\n".join(L), len(entries)


def readme(history, n_fast=0):
    L = ["# 3x3 PBs", "",
         "Personal-best averages, with the full solve list and stats behind each one. "
         "New here? [What's in this repo →](ABOUT.md)",
         "Generated by `scripts/build.py` — don't edit this file by hand.", "",
         "## Current PBs", "",
         "| Event | PB | Date | Stats |", "|---|---|---|---|"]
    for ev in EVENTS:
        if history.get(ev):
            cur = history[ev][0]
            L.append(f"| **{ev}** | **{fmt(cur['average'])}** | {cur['date']} | "
                     f"[details]({cur['page']}) |")
    L += ["", f"**[Fast solve bank →](fast-solves/README.md)** ({n_fast} solve{'s' if n_fast != 1 else ''})", "",
          "![PB progression](stats/progression.png)", "", "## PB history", "",
          "Newest first. Each new PB pushes the older ones down.", ""]
    for ev in EVENTS:
        rows = history.get(ev)
        if not rows:
            continue
        L += [f"### {ev}", "", "| Date | Time | Improvement | σ | σ / mean | Stats |",
              "|---|---|---|---|---|---|"]
        for i, r in enumerate(rows):
            older = rows[i + 1] if i + 1 < len(rows) else None
            imp = f"−{older['average'] - r['average']:.2f}" if older else "first recorded"
            t = f"**{fmt(r['average'])}**" if i == 0 else fmt(r["average"])
            sd = "—" if r["std"] is None else f"{r['std']:.2f}"
            cv = "—" if r["cv"] is None else f"{100 * r['cv']:.1f}%"
            L.append(f"| {r['date']} | {t} | {imp} | {sd} | {cv} | [details]({r['page']}) |")
        L.append("")
    return "\n".join(L)


# ---------------------------------------------------------------- main

def main():
    history = {}
    for ev in EVENTS:
        files = sorted((RECORDS / ev).glob("*.txt"), key=file_key)
        rows, prev = [], None
        for f in files:  # oldest first, so each knows the PB before it
            day = file_label(f)  # "2026-09-25", or "2026-09-25 (#2)" for a same-day repeat
            solves, notes, claimed = parse_file(f)
            want = 1 if ev == "single" else int(ev[2:])
            if len(solves) != want:
                raise SystemExit(f"{f}: expected {want} solves, found {len(solves)}")
            times = [s["time"] for s in solves]
            avg, trimmed = (times[0], set()) if ev == "single" else average(times)
            if claimed is not None and abs(claimed - avg) > 0.005:
                print(f"warning: {f.name}: csTimer says {fmt(claimed)}, computed {fmt(avg)}")
            if prev and avg >= prev["average"]:
                print(f"warning: {f.name} ({fmt(avg)}) is not faster than {prev['date']} "
                      f"({fmt(prev['average'])})")

            outdir = STATS / ev / f.stem
            outdir.mkdir(parents=True, exist_ok=True)
            row = {"date": day, "day": file_key(f)[0].isoformat(), "average": avg, "std": None, "cv": None,
                   "page": f"stats/{ev}/{f.stem}/README.md",
                   "recon": any(s["recon"] for s in solves)}
            if ev == "single":
                (outdir / "README.md").write_text(single_page(day, solves[0], notes, prev))
                rows.append(row)
                prev = row
                print(f"{ev:>6}  {day}  {fmt(avg)}")
                continue

            st = describe(times)
            row["std"], row["cv"] = st["std"], st["cv"]
            plot = plot_numberline if len(times) <= 12 else plot_distribution
            plot(ev, day, times, trimmed, avg, st, outdir / "distribution.png", solves=solves)
            plot_sequence(ev, day, times, trimmed, avg, outdir / "sequence.png")
            (outdir / "README.md").write_text(
                session_page(ev, day, solves, notes, avg, trimmed, st, prev))
            (outdir / "stats.json").write_text(json.dumps(
                {"event": ev, "date": day, "average": avg,
                 **{k: (round(float(v), 4) if isinstance(v, (float, np.floating)) else int(v))
                    for k, v in st.items()},
                 "times": [None if math.isinf(t) else t for t in times]}, indent=2))

            rows.append(row)
            prev = row
            print(f"{ev:>6}  {day}  {fmt(avg)}")
        history[ev] = rows[::-1]  # newest first

    plot_progression(history, STATS / "progression.png")
    (ROOT / "fast-solves").mkdir(exist_ok=True)
    page, n_fast = fast_solves_page()
    (ROOT / "fast-solves" / "README.md").write_text(page)
    (ROOT / "README.md").write_text(readme(history, n_fast))


if __name__ == "__main__":
    main()
