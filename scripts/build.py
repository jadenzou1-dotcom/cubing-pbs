#!/usr/bin/env python3
"""Rebuild every stats page, chart, and the root README from records/.

Usage:  python3 scripts/build.py

Each file in records/<event>/YYYY-MM-DD.txt is one PB. The file name gives
the date; the times inside give the average. More than one PB of the same
event on the same day: YYYY-MM-DD_2.txt, YYYY-MM-DD_3.txt, ... (in the order
they happened; the plain name counts as #1).

fast-solves/YYYY-MM-DD[_N].txt holds hand-picked good solves (one solve per
file, same format, reconstruction optional). They get move-count metrics but
no distributions, and never affect PBs. A csTimer export can be
pasted in whole (its header lines are skipped, and a "single: 9.90" or
"avg of 5: 13.53" line is checked against what the script computes).
Two input formats work:

  numbered (with scrambles)       comma-separated (times only)
  1. (14.53)   D' L' U2 ...       15.05, 13.86, (11.38), 17.14
  2. 12.41   F2 U2 F2 ...         13.29, 17.90, 15.59

Parentheses are optional and ignored: the script decides which solves get
trimmed itself. "17.03+" means a +2 already included in 17.03 (csTimer style).
"DNF" / "DNF(14.20)" count as the worst possible solve. Lines starting with #
are notes and appear on the stats page.

Optional reconstruction: lines starting with ">" right under a numbered solve
belong to that solve. Use // for step comments:

  1. 9.90   R2 B2 L2 F D2 ...
  > z2 // inspection
  > D R' F D' // cross
  > U R U' R' // F2L 1
"""

